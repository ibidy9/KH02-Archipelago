"""Export generation's access catalog to readable Lua; never install a pack."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def lua(value, depth=0):
    """Keep arrays ordered and quote keys explicitly for stable, reviewable output."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (dict, list)):
        entries = (
            [("[" + json.dumps(k, ensure_ascii=False) + "] = ", v) for k, v in value.items()]
            if isinstance(value, dict)
            else [("", v) for v in value]
        )
        if not entries:
            return "{}"
        return "{\n" + ",\n".join(
            "    " * (depth + 1) + key + lua(item, depth + 1)
            for key, item in entries
        ) + "\n" + "    " * depth + "}"
    return json.dumps(value, ensure_ascii=False)


def export(check=False):
    source = ROOT / "worlds/kh02/data/access-rules-v261.json"
    target = ROOT / "poptracker/kh02-ap/scripts/shared-access-rules.lua"
    text = "-- Generated by tools/export_tracker_rules.py; edit the JSON catalog.\nreturn "
    text += lua(json.loads(source.read_text(encoding="utf-8"))) + "\n"
    if check:
        if target.read_text(encoding="utf-8") != text:
            raise ValueError("Tracker access rules are stale; run the exporter")
    else:
        target.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    export(parser.parse_args().check)
